t1 = (10, 20, 30, 40)
t2 = (50, 60)

# Concatenation
print("Concatenation:", t1 + t2)

# Repetition
print("Repetition:", t1 * 2)

# Indexing
print("Indexing:", t1[2])

# Negative indexing
print("Negative indexing:", t1[-1])

# Slicing
print("Slicing:", t1[1:3])

# Membership
print("Membership:", 20 in t1)

# Length
print("Length:", len(t1))

# Minimum
print("Minimum:", min(t1))

# Maximum
print("Maximum:", max(t1))